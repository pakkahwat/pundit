// เรียงฉายาจากยาวไปสั้นครั้งเดียวตอนโหลดโมดูล — สำคัญมากเพราะฉายาสั้นมักเป็นส่วนหนึ่งของฉายายาว
// ("เรอัล โซเซียดัด" มีคำว่า "เรอัล" ที่เป็นฉายาของ Real Madrid อยู่ข้างใน ถ้าเทียบตัวสั้นก่อน
// พาดหัว "ราชันบดเรอัล โซเซียดัด" จะกลายเป็นแมตช์ของ Real Madrid สองทีม)
const ALIASES_BY_LENGTH = Object.entries(TEAM_ALIASES)
  .flatMap(([team, aliases]) => aliases.map((alias) => ({ team, alias })))
  .sort((a, b) => b.alias.length - a.alias.length);

/**
 * หาว่าพาดหัวพูดถึงทีมไหนบ้าง — คืนตามลำดับที่โผล่ในพาดหัว มากสุด 2 ทีม
 *
 * จำกัดที่ 2 เพราะเกินกว่านั้นแปลว่าเป็นบทความสรุปหลายเกม ซึ่งไม่มีภาพเดียวที่แทนได้อยู่แล้ว
 * สู้ใช้ภาพกลาง ๆ ของหมวดนั้นดีกว่า
 *
 * knownTeams (ถ้าส่งมา) คือชื่อทีมที่อยู่ในฤดูกาลนั้นจริง ๆ จาก DB — ใช้กรองไม่ให้ฉายาที่พ้องกัน
 * ข้ามลีกไปจับทีมที่ไม่ได้เล่นในลีกนั้น
 */
export function detectTeamsInTitle(
  title: string,
  knownTeams?: string[],
): string[] {
  const found: { team: string; at: number }[] = [];
  // ตัดข้อความส่วนที่จับได้ออกไปเรื่อย ๆ กันไม่ให้ฉายาสั้นไปจับซ้ำในที่เดิม
  let remaining = title;

  for (const { team, alias } of ALIASES_BY_LENGTH) {
    if (found.some((entry) => entry.team === team)) continue;
    const at = remaining.indexOf(alias);
    if (at < 0) continue;
    // ลิสต์ว่างต้องนับเป็น "ไม่มีข้อมูลให้กรอง" ไม่ใช่ "ไม่มีทีมไหนถูกต้องเลย" — บทความที่เขียน
    // วันไม่มีบอล (ข่าวตลาดซื้อขาย) source มีลิสต์ทีมว่าง ถ้าเช็คแค่ truthy ฉายาทุกตัวจะถูก
    // คัดทิ้งหมด แล้วชั้นภาพสนาม/โลโก้ก็ไม่มีวันทำงานทั้งที่พาดหัวเอ่ยชื่อทีมชัด ๆ (บั๊กจริงที่เจอ)
    if (
      knownTeams &&
      knownTeams.length > 0 &&
      !knownTeams.some((known) => sameTeam(known, team))
    ) {
      continue;
    }
    found.push({ team, at: title.indexOf(alias) });
    remaining = remaining.slice(0, at) + " ".repeat(alias.length) +
      remaining.slice(at + alias.length);
  }

  return found
    .sort((a, b) => a.at - b.at)
    .slice(0, 2)
    .map((entry) => entry.team);
}
